const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const moduleContext = { exports: {}, Uint8Array };
vm.createContext(moduleContext);
vm.runInContext(ts.transpile(fs.readFileSync(path.join(__dirname, '../lib/discern-image.ts'), 'utf8'), { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 }), moduleContext);
const { imageGeometry, zoomAt, paintLine, regionFromPixels, pixelsFromRegion } = moduleContext.exports;
const original = { zoom: 2, x: 31, y: -17 };
const before = imageGeometry(1200, 600, 800, 700, original);
const cursor = { x: 213, y: 407 };
const next = zoomAt(original, 3.5, cursor.x, cursor.y, 800, 700);
const after = imageGeometry(1200, 600, 800, 700, next);
assert.ok(Math.abs((cursor.x - before.left) / before.width - (cursor.x - after.left) / after.width) < 1e-12);
assert.ok(Math.abs((cursor.y - before.top) / before.height - (cursor.y - after.top) / after.height) < 1e-12);
assert.equal(zoomAt(original, 100, 0, 0, 800, 700).zoom, 16);
assert.equal(zoomAt(original, 0.01, 0, 0, 800, 700).zoom, 1);
const pixels = new Uint8Array(40 * 20);
paintLine(pixels, 40, 20, { x: 4, y: 10 }, { x: 35, y: 10 }, 2, false);
for (let x = 4; x < 35; x++) assert.equal(pixels[10 * 40 + x], 1, 'Fast strokes must have no gaps');
const saved = pixels.slice();
paintLine(pixels, 40, 20, { x: 18, y: 10 }, { x: 18, y: 10 }, 3, true);
assert.equal(pixels[10 * 40 + 18], 0);
assert.equal(saved[10 * 40 + 18], 1, 'History snapshots must be independent');
const region = regionFromPixels(pixels, 40, 20, 'manual');
assert.equal(region.manual, true);
const roundtrip = pixelsFromRegion(region, 40, 20);
assert.deepEqual(Array.from(roundtrip), Array.from(pixels), 'RLE masks preserve every selected pixel');
assert.equal(regionFromPixels(new Uint8Array(800), 40, 20, 'empty'), null);
const edge = new Uint8Array(800);
paintLine(edge, 40, 20, { x: 0, y: 0 }, { x: 0, y: 0 }, 10, false);
assert.equal(edge[0], 1);
assert.equal(edge[39], 0, 'Brush must not wrap across rows');
console.log('Passed: cursor-anchored zoom, zoom limits, continuous strokes, erasing, immutable snapshots, exact mask roundtrip, empty selections, and edge clipping.');

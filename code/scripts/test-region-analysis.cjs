const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const context = { exports: {}, AbortController };
vm.runInNewContext(ts.transpile(fs.readFileSync('lib/region-analysis.ts','utf8'), { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 }), context);
const { createRegionAnalysisManager, regionLabel } = context.exports;
const defer = () => { let resolve; const promise = new Promise(done => resolve = done); return { promise, resolve }; };
(async () => {
 const states = new Map(), results = new Map();
 const manager = createRegionAnalysisManager({ onState: (id, state) => states.set(id, state), onResult: (id,result) => results.set(id,result) });
 let calls = 0;
 const a = defer(), b = defer();
 const first = manager.run('one', async () => { calls++; return a.promise; });
 const duplicate = manager.run('one', async () => { throw new Error('Duplicate must never execute'); });
 assert.equal(first, duplicate);
 const second = manager.run('two', async () => { calls++; return b.promise; });
 await Promise.resolve(); assert.equal(calls,2);
 b.resolve('second-result'); await second;
 assert.equal(states.get('one').status,'analyzing'); assert.equal(states.get('two').status,'complete');
 assert.equal(results.get('two'),'second-result'); assert.equal(results.has('one'),false);
 a.resolve('first-result'); await first;
 assert.equal(results.get('one'),'first-result');
 const old = defer(); const stale = manager.run('same-id', async () => old.promise);
 manager.reset(); states.clear(); results.clear();
 const fresh = manager.run('same-id',async () => 'new-image'); await fresh;
 old.resolve('old-image'); await stale;
 assert.equal(results.get('same-id'),'new-image');
 const failed = await manager.run('error', async () => { throw new Error('Network failure'); });
 assert.equal(failed,false); assert.equal(states.get('error').status,'error');
 await manager.run('error',async () => 'retry-success'); assert.equal(states.get('error').status,'complete');
 // Fill both slots, queue the remainder, and move a selected region forward.
 const queueStates = new Map(), started = [], gates = new Map();
 const queuedManager = createRegionAnalysisManager({ onState:(id,state)=>queueStates.set(id,state), onResult() {} });
 let active = 0, maximum = 0;
 const task = id => async signal => {
   started.push(id); active++; maximum=Math.max(maximum,active);
   await gates.get(id).promise;
   active--; return id;
 };
 for (const id of ['a','b','c','d','e','f']) gates.set(id,defer());
 const jobs = new Map();
 for (const id of gates.keys()) jobs.set(id,queuedManager.run(id,task(id)));
 await Promise.resolve();
 assert.deepEqual(started,['a','b']);
 assert.equal(queueStates.get('f').status,'queued');
 assert.equal(queuedManager.run('f',task('f'),true),jobs.get('f'));
 gates.get('a').resolve(); await jobs.get('a');
 for(let i=0;i<8;i++) await Promise.resolve();
 assert.deepEqual(started,['a','b','f']);
 gates.get('b').resolve(); gates.get('f').resolve();
 await jobs.get('b'); await jobs.get('f');
 for(let i=0;i<8;i++) await Promise.resolve();
 assert.deepEqual(started,['a','b','f','c','d']);
 gates.get('c').resolve(); gates.get('d').resolve();
 await jobs.get('c'); await jobs.get('d');
 for(let i=0;i<8;i++) await Promise.resolve();
 gates.get('e').resolve(); await jobs.get('e');
 assert.equal(maximum,2);
 // Reset cancels waiting work without launching it, even if active tasks ignore abort.
 const resetManager = createRegionAnalysisManager({ onState() {}, onResult(){throw new Error('Stale result');} },1);
 const held = defer(); let queuedRan=false, activeSignal;
 const running = resetManager.run('active',async signal=>{activeSignal=signal;return held.promise;});
 const waiting = resetManager.run('waiting',async()=>{queuedRan=true;return 'wrong';});
 await Promise.resolve(); resetManager.reset();
 assert.equal(await waiting,false); assert.equal(await running,false);
 assert.equal(activeSignal.aborted,true); assert.equal(queuedRan,false);
 held.resolve('stale');
 assert.equal(regionLabel(), 'Unidentified symbol');
 assert.equal(regionLabel({name:'Visual proposal',visualIdentification:{status:'likely'},identification:{status:'unidentified'}}),'Visual proposal', 'Visual assessment must remain visible independently of legacy reference state');
 assert.equal(regionLabel({name:'Celtic knot',identification:{status:'unidentified'}}), 'Unidentified symbol');
 assert.equal(regionLabel({name:'A researched identity',identification:{status:'supported'}}), 'A researched identity');
 console.log('Passed: bounded concurrency, queue draining, selected-region priority, cancellation, request deduplication, independent region states/results, stale-image isolation, retry, and neutral pending/unidentified labels.');
})().catch(error => { console.error(error);process.exitCode=1; });
